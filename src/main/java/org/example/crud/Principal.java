package org.example.crud;

public class Principal {

    private String name;
    private long mobile;

    public void setName(String name) {
        this.name = name;
    }

    public void setMobile(long mobile) {
        this.mobile = mobile;
    }

    public String getName() {
        return name;
    }
    public long getMobile() {
        return mobile;
    }

}
